import {readFile,writeFile,rename,mkdir,appendFile} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export const sourceUrl='https://www.stylevana.com/en_US/cosrx-advanced-snail-96-mucin-power-essence-100ml10777.html';
// This schema describes a manually reviewed observation, not an API license.
export function validate(row, today=new Date().toISOString().slice(0,10)) {
  if(!row || typeof row!=='object' || Array.isArray(row)) throw Error('invalid record');
  const required={productId:'2',market:'US',currency:'USD',retailer:'Stylevana US',size:'100ml',quantity:1,method:'manual',url:sourceUrl};
  for(const [key,value] of Object.entries(required)) if(row[key]!==value) throw Error('mismatch: '+key);
  if(typeof row.amount!=='number'||!Number.isFinite(row.amount)||row.amount<=0||row.amount>10000||Math.abs(row.amount*100-Math.round(row.amount*100))>1e-7) throw Error('invalid amount');
  if(typeof row.observedOn!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(row.observedOn)||Number.isNaN(Date.parse(row.observedOn))||new Date(row.observedOn).toISOString().slice(0,10)!==row.observedOn||row.observedOn>today) throw Error('invalid observation date');
  if(row.shipping!==null||row.tax!==null||row.availability!=='unknown') throw Error('unverified shipping/tax/stock');
  if(typeof row.evidence!=='string'||!row.evidence.trim()||row.evidence.length>1000) throw Error('evidence required');
  return Object.fromEntries([...Object.keys(required),'amount','observedOn','shipping','tax','availability','evidence'].map(k=>[k,row[k]]));
}
export function ingest(existing,incoming,today){
  if(!Array.isArray(existing)||!Array.isArray(incoming)||!incoming.length) throw Error('nonempty input array required');
  const records=[];let added=0,duplicates=0;
  for(const [group,isNew] of [[existing,false],[incoming,true]])for(const raw of group){
    const row=validate(raw,today),same=records.find(r=>r.productId===row.productId&&r.url===row.url&&r.observedOn===row.observedOn);
    if(same){if(same.amount!==row.amount) throw Error('conflicting same-day observation: exact timestamps required for intraday prices');if(isNew)duplicates++;continue;}
    records.push(row);if(isNew)added++;
  }
  records.sort((a,b)=>a.observedOn.localeCompare(b.observedOn));
  return {records,added,duplicates};
}
export function browserModule(records){
  if(!records.length)throw Error('no observations');
  return '// Generated by scripts/price-pipeline.mjs. Manual observations; not live prices.\nexport const priceObservations = '+JSON.stringify(records,null,2)+';\n';
}
async function atomic(path,content){await mkdir(dirname(path),{recursive:true});const tmp=path+'.tmp-'+process.pid;await writeFile(tmp,content);await rename(tmp,path);}
export async function run(inputPath,root){
  const ledger=resolve(root,'data/price-observations.json'),output=resolve(root,'dist/observed-data.js');
  let existing=[];
  try{existing=JSON.parse(await readFile(ledger,'utf8'));}catch(e){if(e.code!=='ENOENT')throw e;}
  const incoming=JSON.parse(await readFile(inputPath,'utf8'));
  const result=ingest(existing,incoming);
  // Ledger is authoritative. Derived module is safe to rebuild on the next run.
  await atomic(ledger,JSON.stringify(result.records,null,2)+'\n');
  await atomic(output,browserModule(result.records));
  return {added:result.added,duplicates:result.duplicates,total:result.records.length,latest:result.records.at(-1).observedOn};
}
